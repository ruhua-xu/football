def test_preflight_correction_never_reads_provider_bytes_or_opens_database(
    writer, capsys, monkeypatch, bad
):
    lane = writer
    request = reviewed_request(lane, capsys).model_dump(mode="json")
    if bad == "missing-version":
        request["intent"].pop("schema_version")
    elif bad == "untrusted-review":
        request["reviewer_authority"]["evidence_sha256"] = "0" * 64
    elif bad == "changed-intent":
        request["intent"]["candidate"]["home_goals"] = 9
    else:
        path = (
            lane.root / request["intent"]["evidence"]["adapter"]["evidence_reference"]
        )
        adapter = json.loads(path.read_bytes())
        if bad == "v1-adapter":
            adapter["schema_version"] = "TRAINING_JSON_ADAPTER_V1"
        elif bad == "missing-status":
            adapter["result"].pop("status")
        else:
            adapter["status_rules"].append(adapter["status_rules"][0])
        request["intent"]["evidence"]["adapter"] = admission_cases.write_evidence(
            lane.root, path.name, adapter
        ).model_dump(mode="json")
    original_read = cli.LocalTrainingEvidence.read
    reads = []

    def no_provider(self, reference, expected_sha256=None):
        if reference in {
            "fixture.json",
            "scope.json",
            "result.json",
            "correction-result-1.json",
        }:
            reads.append(reference)
            pytest.fail("preflight read provider bytes")
        return original_read(self, reference, expected_sha256)

    monkeypatch.setattr(cli.LocalTrainingEvidence, "read", no_provider)
    calls = previous.no_database_calls(monkeypatch)
    result, error = previous.invoke(
        lane, "correction-admit", request, capsys, database="absent.db"
    )
    assert result == 2 and error["code"] == "INVALID_LOCAL_INPUT"
    assert error["persistence"] == "NO_DATABASE_OPENED"
    assert not reads and not calls
    assert not (lane.root / "absent.db").exists()


