def context_request(lane, ids=(), cutoff=None):
    return dict(
        base_admissions=(lane.base_pin,),
        correction_ids=ids,
        source_cutoffs={
            "source": cutoff or admission_cases.SOURCE + timedelta(days=30)
        },
    )


def context_response(lane, capsys, ids=(), cutoff=None):
    response = public(
        lane, "correction-context", context_request(lane, ids, cutoff), capsys
    )
    assert response["status"] == "VERIFIED"
    return response["result"]


