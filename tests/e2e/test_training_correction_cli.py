@pytest.mark.parametrize("bad", ["missing-raw", "wrong-reviewer", "after-insert"])
def test_correction_admit_failure_is_atomic(writer, capsys, monkeypatch, bad):
    lane = writer
    request = reviewed_request(lane, capsys)
    if bad == "missing-raw":
        (lane.root / "correction-result-1.json").unlink()
    elif bad == "wrong-reviewer":
        doc = json.loads(
            (lane.root / request.reviewer_evidence.evidence_reference).read_bytes()
        )
        doc["authorized_reviewer"] = "not-authorized"
        review = admission_cases.write_evidence(lane.root, "wrong-reviewer.json", doc)
        request = request.model_copy(update={"reviewer_evidence": review})

    def fail_after_insert(
        connection, cursor, statement, parameters, context, executemany
    ):
        if bad == "after-insert" and statement.startswith(
            "INSERT INTO training_correction_admissions"
        ):
            raise OSError(previous.SECRET)

    before = correction_cases.counts(lane)
    event.listen(Engine, "after_cursor_execute", fail_after_insert)
    try:
        result, error = previous.invoke(lane, "correction-admit", request, capsys)
    finally:
        event.remove(Engine, "after_cursor_execute", fail_after_insert)
    assert result == 1 and error["code"] == "OPERATION_REJECTED"
    assert error["persistence"] == "ATOMIC_NO_NEW_ROWS"
    assert "failed atomically" in error["message"]
    assert correction_cases.counts(lane) == before


