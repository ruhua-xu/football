def wire_correction_helpers(lane, capsys, monkeypatch):
    # Only fixture entry points are routed; every CLI call constructs fresh real
    # repositories and performs the complete rights/evidence/transaction checks.
    monkeypatch.setattr(
        lane.repo,
        "capture_local_json",
        lambda **values: public(
            lane, "capture", values, capsys, TrainingCaptureReceiptV1
        ),
    )
    monkeypatch.setattr(
        lane.corrections,
        "capture_reference",
        lambda receipt_id, **values: public(
            lane,
            "correction-reference",
            dict(receipt_id=receipt_id, **values),
            capsys,
            CorrectionCaptureRefV2,
        ),
    )

    def prepare(**values):
        lane.prepare_request = values
        lane.preview = public(lane, "correction-prepare", values, capsys)
        return TrainingCorrectionIntentV2.model_validate(lane.preview["result"])

    monkeypatch.setattr(lane.corrections, "prepare", prepare)


