        assert (
            manifest.content_payload.history.context_pin.context_root
            == output["context_root"]
        )
        assert (
            public(lane, "manifest", request, capsys, TrainingHistoryManifestV1)
            == manifest
        )
        release = approve(context, manifest, "cli-corrected-approval", recorded[0])
        assert context.repo.load_release(releases[0].artifact_id) == releases[0]
        with pytest.raises(ValueError, match="correction"):
            context.repo.authorization(releases[0].artifact_id, lane.clock())

        def target_plan(*args):
            return public(
                lane,
                "target-plan",
                dict(zip(cli.TargetPlanRequestV1.model_fields, args, strict=True)),
                capsys,
                ProductionTargetAcceptancePlanV1,
            )

        monkeypatch.setattr(context.repo, "seal_target_plan", target_plan)
        return release

