            schema_version="PRODUCTION_QUANT_MANIFEST_REQUEST_V2",
            correction_context=output["correction_context"],
            context_registered_at_utc=output["context_registered_at_utc"],
            selection_cutoff_at_utc=admission_cases.SOURCE + timedelta(days=30),
            exclude_match_ids=(),
